import { normalizedProjectName } from "../config/workspace-config.ts";
import type { GraphEdge, WorkspaceGraph } from "./workspace-graph.ts";

/**
 * A node id. Prefixed because a bare name could be a Mermaid keyword such as `end`, and
 * built from the normalized name because validation guarantees those are unique.
 */
function nodeId(project: string): string {
  return `p_${normalizedProjectName(project).toLowerCase()}`;
}

function edgeLine({ upstream, downstream, type, confirmed, source }: GraphEdge): string {
  const arrow = confirmed ? "-->" : "-.->";
  const label = confirmed ? type : `${type} (${source})`;
  return `  ${nodeId(upstream)} ${arrow}|"${label}"| ${nodeId(downstream)}`;
}

function orderLine(group: readonly string[], index: number): string {
  const note = group.length > 1 ? " (a cycle: the Operator sets the order)" : "";
  return `${index + 1}. ${group.join(", ")}${note}`;
}

/**
 * The content of `graph.md`. It holds no timestamps and takes its order from the graph's
 * canonical form, so the same graph always renders byte-identically.
 */
export function renderGraphDocument(graph: WorkspaceGraph): string {
  return [
    "<!-- Generated by Foreman from workspace.yaml. Edits here are overwritten. -->",
    "",
    "# Workspace Graph",
    "",
    "```mermaid",
    "flowchart LR",
    ...graph.projects.map((project) => `  ${nodeId(project)}["${project}"]`),
    ...graph.edges.map(edgeLine),
    "```",
    "",
    "Arrows point from Upstream to Downstream. Dashed Edges are unconfirmed and don't affect order.",
    "",
    "## Order",
    "",
    ...graph.order.map(orderLine),
    "",
  ].join("\n");
}
