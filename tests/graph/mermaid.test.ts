import { expect, test } from "bun:test";
import { renderGraphDocument } from "../../src/graph/mermaid.ts";
import { createWorkspaceGraph, type DeclaredEdge } from "../../src/graph/workspace-graph.ts";
import { mermaidBlock, parseFlowchart } from "../helpers/mermaid.ts";

const PROJECTS = ["notifier", "orders-api", "catalog-api", "shared_types"];
const EDGES: DeclaredEdge[] = [
  { from: "catalog-api", to: "shared_types", type: "shares-lib", source: "confirmed" },
  { from: "orders-api", to: "catalog-api", type: "calls-api", source: "confirmed" },
  { from: "orders-api", to: "notifier", type: "publishes-event", source: "detected" },
  { from: "notifier", to: "orders-api", type: "consumes-event", source: "confirmed" },
  { from: "orders-api", to: "shared_types", type: "depends-on", source: "detected" },
];

function render(projects = PROJECTS, edges = EDGES) {
  return renderGraphDocument(createWorkspaceGraph({ projects, edges }));
}

test("the document has this exact form", () => {
  expect(render()).toBe(`<!-- Generated by Foreman from workspace.yaml. Edits here are overwritten. -->

# Workspace Graph

\`\`\`mermaid
flowchart LR
  p_catalog_api["catalog-api"]
  p_notifier["notifier"]
  p_orders_api["orders-api"]
  p_shared_types["shared_types"]
  p_catalog_api -->|"calls-api"| p_orders_api
  p_orders_api -->|"consumes-event"| p_notifier
  p_orders_api -.->|"publishes-event (detected)"| p_notifier
  p_shared_types -->|"shares-lib"| p_catalog_api
  p_shared_types -.->|"depends-on (detected)"| p_orders_api
\`\`\`

Arrows point from Upstream to Downstream. Dashed Edges are unconfirmed and don't affect order.

## Order

1. shared_types
2. catalog-api
3. orders-api
4. notifier
`);
});

test("the same input renders byte-identically, whatever order it was declared in", () => {
  expect(render()).toBe(render());
  expect(render(PROJECTS.toReversed(), EDGES.toReversed())).toBe(render());
});

test("AC-74: the Mermaid is valid, and contains every Project and Edge with its direction normalized", () => {
  const { projects, edges } = parseFlowchart(mermaidBlock(render()));

  expect(projects.toSorted()).toEqual(PROJECTS.toSorted());
  expect(edges).toHaveLength(EDGES.length);
  expect(edges).toContainEqual({
    upstream: "catalog-api",
    downstream: "orders-api",
    type: "calls-api",
    dashed: false,
  });
  expect(edges).toContainEqual({
    upstream: "orders-api",
    downstream: "notifier",
    type: "publishes-event",
    dashed: true,
  });
});

test("Project names that are Mermaid keywords stay valid", () => {
  const keywords = ["end", "graph", "subgraph", "style", "click", "default", "class", "flowchart", "o", "x"];
  const edges: DeclaredEdge[] = keywords.slice(1).map((name) => ({
    from: name,
    to: "end",
    type: "calls-api",
    source: "confirmed",
  }));

  const { projects, edges: parsed } = parseFlowchart(mermaidBlock(render(keywords, edges)));

  expect(projects.toSorted()).toEqual(keywords.toSorted());
  expect(parsed).toHaveLength(edges.length);
});

test("a cycle is shown as one step of the order, and says the Operator decides", () => {
  const document = render(
    ["x", "y"],
    [
      { from: "x", to: "y", type: "calls-api", source: "confirmed" },
      { from: "y", to: "x", type: "calls-api", source: "confirmed" },
    ],
  );

  expect(document).toContain("1. x, y (a cycle: the Operator sets the order)\n");
});

test("a graph with no Projects still renders a valid flowchart", () => {
  const document = render([], []);

  expect(parseFlowchart(mermaidBlock(document))).toEqual({ projects: [], edges: [] });
});
